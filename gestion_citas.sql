-- Ejecutar conectado a la base gestion_citas, creada previamente en PostgreSQL.
-- Los nombres id_cliente e id_cita corresponden a los modelos y DAO del proyecto.
-- Crea tablas nuevas; no modifica tablas existentes ni elimina datos.
BEGIN;

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(120) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS cita_tecnica (
    id_cita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    tipo_servicio VARCHAR(80) NOT NULL CHECK (btrim(tipo_servicio) <> ''),
    descripcion VARCHAR(255) NOT NULL CHECK (btrim(descripcion) <> ''),
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_cita_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    CONSTRAINT ck_cita_estado CHECK (
        estado IN ('Pendiente', 'En proceso', 'Finalizada', 'Cancelada')
    )
);

CREATE INDEX IF NOT EXISTS idx_cita_cliente ON cita_tecnica (id_cliente);
CREATE INDEX IF NOT EXISTS idx_cita_fecha ON cita_tecnica (fecha);
CREATE INDEX IF NOT EXISTS idx_cita_estado_fecha ON cita_tecnica (estado, fecha);

COMMIT;
